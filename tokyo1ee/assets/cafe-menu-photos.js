function renderCafeMenuPhotos(snack){
  const photos=(cafeMenuPhotos[snack.id]||[]).filter(photo=>photo.src!==snack.photo.src);
  if(!photos.length)return '';
  const esc=photoEscape;
  return `<div class="cafe-menu-photos"><h6>메뉴 사진으로 고르기</h6><div class="cafe-menu-grid">${photos.map(photo=>`<figure class="cafe-menu-photo">
    <button type="button" data-photo="${esc(photo.key)}" aria-label="${esc(photo.title)} 메뉴 사진 크게 보기"><img src="${esc(photo.src)}" width="${photo.width}" height="${photo.height}" loading="lazy" decoding="async" alt="${esc(photo.title+' · '+photo.caption)}"><span aria-hidden="true">⤢</span></button>
    <figcaption><strong>${esc(photo.title)}</strong><span lang="ja">${esc(photo.jp)}</span><small>${esc(photo.caption)}</small><a href="${esc(photo.source)}" target="_blank" rel="noopener noreferrer">메뉴·사진 출처 ↗</a></figcaption>
  </figure>`).join('')}</div></div>`;
}
