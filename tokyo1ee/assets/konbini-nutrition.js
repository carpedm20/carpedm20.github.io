const nutritionDailyReference = {kcal:2000, proteinG:55};
function nutritionPercent(value,reference){
  const pct=value/reference*100;
  return pct>0&&pct<1 ? pct.toFixed(1) : String(Math.round(pct));
}
function renderKonbiniNutrition(item){
  const n=konbiniNutrition[item.id];
  if(!n)return '';
  const known=value=>typeof value==='number'&&Number.isFinite(value)&&value>=0;
  const metric=(label,value,unit,reference)=>`<div><dt>${label}</dt><dd>${known(value)?`<strong>${value.toLocaleString('ko-KR',{maximumFractionDigits:1})}</strong> <span class="nutrition-unit">${unit}</span><small>하루 기준 ${nutritionPercent(value,reference)}%</small>`:'<span class="nutrition-unknown">미확인</span><small>포장 표기 확인</small>'}</dd></div>`;
  const sourceLabel=n.status==='partial'?'공식 포장 표기':n.status==='reference'?'지난 공식 영양정보':'공식 영양정보';
  return `<section class="nutrition-facts" data-nutrition-id="${item.id}" data-nutrition-status="${n.status}" aria-describedby="nutritionGuide" aria-label="${photoEscape(item.ko)} 영양정보">
    <p class="nutrition-serving">${photoEscape(n.servingKo||'상품 포장')} 기준</p>
    ${n.status==='reference'?`<p class="nutrition-note nutrition-reference">${photoEscape(n.displayNote)}</p>`:''}
    <dl>${metric('열량',n.kcal,'kcal',nutritionDailyReference.kcal)}${metric('단백질',n.proteinG,'g',nutritionDailyReference.proteinG)}</dl>
    ${n.displayNote&&n.status!=='reference'?`<p class="nutrition-note">${photoEscape(n.displayNote)}</p>`:''}
    ${(known(n.kcal)||known(n.proteinG))&&n.source!==item.url?`<a class="nutrition-source" href="${photoEscape(n.source)}" target="_blank" rel="noopener noreferrer">${sourceLabel} ↗</a>`:''}
  </section>`;
}

