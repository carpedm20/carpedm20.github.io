function streetSnacksForDay(){
  const plan=day===3?planChoices.shops:day===4?planChoices.night:'base';
  return streetSnackStops.filter(s=>s.day===day&&(!s.planAreas||s.planAreas.includes(plan)));
}
function streetSnackStopIndex(snack,stops){
  const clusterBySlot={akihabara:'akiba-culture',harajuku:'harajuku-vintage',shibuya:'shibuya-vintage',aoyama:'aoyama-design',hatagaya:'hatagaya-local',ebisu:'ebisu-books',east:'east-art'};
  const cluster=clusterBySlot[snack.slot];
  let index=cluster?stops.findIndex(s=>s.shopCluster===cluster):-1;
  if(index>=0)return index;
  if(snack.slot==='harajuku'&&day===3&&planChoices.shops==='fashion'){
    index=stops.findIndex(s=>s.shopCluster==='aoyama-design');
    if(index>=0)return index;
  }
  const match={
    bigsight:s=>s.title.includes('코미케 자유 탐방'),
    shinbashi:s=>s.foodId==='kushikatsu-tanaka-shimbashi',
    kiyosumi:s=>s.title.includes('강변 산책'),
    shiodome:s=>s.title.includes('시오도메로 이동'),
    shibuya:s=>s.foodId==='kirin-shibuya',
    airport:s=>s.title.includes('하네다공항 이동'),
    gotanda:s=>s.title.includes('플리마켓')
  }[snack.slot];
  if(match)index=stops.findIndex(match);
  return index>=0?index:stops.length-1;
}
